/** @type {Promise<boolean> | null} */
let nativeSupportPromise = null;
/** @type {Promise<void> | null} */
let initPromise = null;

/** @type {Array<{ worker: Worker, busy: boolean }>} */
let pool = [];
/** @type {Map<number, { resolve: Function, reject: Function, slot: object }>} */
const inFlight = new Map();
/** @type {Array<{ buffer: ArrayBuffer, resolve: Function, reject: Function }>} */
const waiting = [];
let nextJobId = 1;

function base64ToBytes(b64) {
  const binary = atob(b64);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
  return bytes;
}

/**
 * Detects native HEIC decoding by actually decoding a tiny real HEIC — never by
 * user-agent sniffing. Cached after the first call.
 *
 * A false negative is harmless (we fall back to WASM, just slower); a false positive
 * would break decoding, so we verify the probe produces a bitmap of the exact expected
 * size rather than trusting that createImageBitmap merely resolved.
 *
 * @returns {Promise<boolean>}
 */
export async function isNativeHeicSupported() {
  if (nativeSupportPromise) return nativeSupportPromise;

  nativeSupportPromise = (async () => {
    if (typeof createImageBitmap !== 'function' || typeof Blob !== 'function') return false;

    try {
      const blob = new Blob([base64ToBytes(PROBE_HEIC_BASE64)], { type: 'image/heic' });
      const bitmap = await createImageBitmap(blob);
      const ok = bitmap.width === 64 && bitmap.height === 64;
      bitmap.close();
      return ok;
    } catch (_) {
      // Chrome/Firefox reject with "source image could not be decoded" — expected.
      return false;
    }
  })();

  return nativeSupportPromise;
}

function spawnWorker() {
  const worker = new Worker(new URL('./decode.worker.js', import.meta.url), { type: 'module' });
  const slot = { worker, busy: false };

  worker.addEventListener('message', (event) => {
    const { type, id, bitmap, width, height, message } = event.data || {};
    const job = inFlight.get(id);
    if (!job) return; // response for a disposed/unknown job

    inFlight.delete(id);
    job.slot.busy = false;

    if (type === 'result') job.resolve({ bitmap, width, height });
    else if (type === 'error') job.reject(new Error(message || 'HEIC decoding failed.'));

    pump();
  });

  // A worker-level failure (e.g. the module failed to load) would otherwise leave every
  // job on this worker hanging forever.
  worker.addEventListener('error', (event) => {
    const reason = new Error(
      (event && event.message) || 'The HEIC decoder crashed while loading.'
    );
    for (const [id, job] of [...inFlight]) {
      if (job.slot === slot) {
        inFlight.delete(id);
        job.reject(reason);
      }
    }
    slot.busy = false;
    pump();
  });

  return slot;
}

function ensurePool() {
  if (pool.length === 0) {
    for (let i = 0; i < POOL_SIZE; i++) pool.push(spawnWorker());
  }
  return pool;
}

/** Hand queued jobs to idle workers. */
function pump() {
  while (waiting.length > 0) {
    const slot = pool.find((s) => !s.busy);
    if (!slot) return;

    const job = waiting.shift();
    const id = nextJobId++;
    slot.busy = true;
    inFlight.set(id, { resolve: job.resolve, reject: job.reject, slot });
    // Transfer the buffer: zero-copy, and the worker owns it from here.
    slot.worker.postMessage({ type: 'decode', id, buffer: job.buffer }, [job.buffer]);
  }
}

/**
 * Warms up the decoder so the first real decode isn't paying for wasm compilation.
 * Safe to call multiple times (and concurrently) — the work happens once.
 *
 * @returns {Promise<void>}
 */
export async function initDecoder() {
  if (initPromise) return initPromise;

  initPromise = (async () => {
    if (await isNativeHeicSupported()) return; // native needs no warmup

    ensurePool();
    // Warm every worker so a burst of parallel decodes doesn't serialise behind N
    // separate wasm compilations.
    //
    // Warmup NEVER rejects and never hangs: it is only an optimisation. If a worker
    // fails to warm we resolve anyway and let the real decodeHeic() call surface the
    // error properly — a broken warmup must not wedge the whole app.
    await Promise.all(
      pool.map(
        (slot) =>
          new Promise((resolve) => {
            const done = () => {
              slot.worker.removeEventListener('message', onMessage);
              clearTimeout(timer);
              resolve();
            };
            const onMessage = (event) => {
              const type = event.data && event.data.type;
              if (type === 'ready' || type === 'error') done();
            };
            const timer = setTimeout(done, 30000);
            slot.worker.addEventListener('message', onMessage);
            slot.worker.addEventListener('error', done, { once: true });
            slot.worker.postMessage({ type: 'init', id: 0 });
          })
      )
    );
  })().catch((err) => {
    initPromise = null; // let a later call retry
    throw err;
  });

  return initPromise;
}

/**
 * Decode one HEIC file's PRIMARY image (Live Photos / bursts decode their primary only).
 * Safe to call concurrently — see the concurrency notes at the top of this file.
 *
 * @param {File | Blob} file
 * @returns {Promise<{ bitmap: ImageBitmap, width: number, height: number }>}
 * @throws {Error} with a human-readable `.message` on a corrupt / non-HEIC input.
 */
export async function decodeHeic(file) {
  if (!file || typeof file.arrayBuffer !== 'function') {
    throw new Error('No file was provided to decode.');
  }
  if (file.size === 0) {
    throw new Error('This file is empty.');
  }

  if (await isNativeHeicSupported()) {
    try {
      // `from-image` so any EXIF orientation the browser knows about is applied for us.
      const bitmap = await createImageBitmap(file, { imageOrientation: 'from-image' });
      return { bitmap, width: bitmap.width, height: bitmap.height };
    } catch (_) {
      // The probe proved native decoding works in general, so a failure here is far more
      // likely a bad file than a capability gap — but fall through to WASM anyway, which
      // is stricter and produces a much better diagnostic than the browser's terse
      // "source image could not be decoded".
    }
  }

  ensurePool();
  const buffer = await file.arrayBuffer();

  return new Promise((resolve, reject) => {
    waiting.push({ buffer, resolve, reject });
    pump();
  });
}

/**
 * Terminate the worker pool and reset state. In-flight decodes reject.
 * A later decodeHeic()/initDecoder() call transparently rebuilds the pool.
 *
 * @returns {void}
 */
export function disposeDecoder() {
  for (const [, job] of inFlight) {
    job.reject(new Error('The decoder was shut down before this file finished.'));
  }
  inFlight.clear();

  for (const job of waiting.splice(0)) {
    job.reject(new Error('The decoder was shut down before this file finished.'));
  }

  for (const slot of pool) slot.worker.terminate();
  pool = [];
  initPromise = null;
  // Native support is a property of the browser, not of the pool — keep it cached.
}
